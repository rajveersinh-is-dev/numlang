def escape_latex(s: str) -> str:
    return s.replace("&", r"\&").replace("_", r"\_").replace("%", r"\%")

def generate_table_reference(ref_rows, results_data_by_bench, sha256_hash: str) -> str:
    lines = [
        make_header(sha256_hash, "bench/data/reference_baselines.csv"),
        r"\begin{table}[t]",
        r"\centering",
        r"\small",
        r"\caption{Direct comparison against canonical literature supercompilers (SPSC, Supero, HOSC) on shared literature benchmarks. Literature speedup reported from published papers; NumLang speedup is measured empirically.}",
        r"\label{tab:reference_supercompilers}",
        r"\begin{tabular}{llllrr}",
        r"\toprule",
        r"\textbf{Benchmark} & \textbf{System} & \textbf{Source Reference} & \textbf{Transformation} & \textbf{Lit. Speedup} & \textbf{NumLang Super} \\",
        r"\midrule",
    ]

    for row in ref_rows:
        bench = row["benchmark"]
        sys_name = escape_latex(row["system"])
        # Shorten reference for table layout
        source = escape_latex(row["source_paper"].split(" - ")[0])
        # Short transformation summary
        notes = escape_latex(row["notes"].split(";")[0])
        if len(notes) > 40:
            notes = notes[:37] + "..."
        lit_speedup = f"{float(row['reported_speedup']):.2f}$\\times$"

        # Find NumLang super speedup from results
        nl_speedup_str = "--"
        if bench in results_data_by_bench and "numlang_super" in results_data_by_bench[bench]:
            s_entry = results_data_by_bench[bench]["numlang_super"]
            if s_entry.get("speedup_vs_baseline"):
                try:
                    s_val = float(s_entry["speedup_vs_baseline"])
                    nl_speedup_str = f"{s_val:.2f}$\\times$"
                except ValueError:
                    pass

        lines.append(
            f"\\texttt{{{bench}}} & {sys_name} & {source} & {notes} & {lit_speedup} & {nl_speedup_str} \\\\"
        )

    lines.extend([
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}",
    ])
    return "\n".join(lines) + "\n"

def main():
    if not RESULTS_CSV.exists():
        print(f"[ERROR] Results file does not exist: {RESULTS_CSV}", file=sys.stderr)
        sys.exit(1)

    GEN_DIR.mkdir(parents=True, exist_ok=True)

    results_hash = compute_sha256(RESULTS_CSV)
    print(f"[INTEGRITY] Results hash: sha256:{results_hash}")

    # Load results.csv
    data_by_bench = {}
    with open(RESULTS_CSV, "r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            b = row["benchmark"]
            c = row["config"]
            if b not in data_by_bench:
                data_by_bench[b] = {}
            data_by_bench[b][c] = row

    # Generate table_benchmarks.tex
    table_bench_tex = generate_table_benchmarks(data_by_bench, results_hash)
    (GEN_DIR / "table_benchmarks.tex").write_text(table_bench_tex, encoding="utf-8")
    print(f"[OK] Generated {GEN_DIR / 'table_benchmarks.tex'}")

    # Generate table_codesize.tex
    table_codesize_tex = generate_table_codesize(data_by_bench, results_hash)
    (GEN_DIR / "table_codesize.tex").write_text(table_codesize_tex, encoding="utf-8")
    print(f"[OK] Generated {GEN_DIR / 'table_codesize.tex'}")

    # Generate table_compiletime.tex
    table_compiletime_tex = generate_table_compiletime(data_by_bench, results_hash)
    (GEN_DIR / "table_compiletime.tex").write_text(table_compiletime_tex, encoding="utf-8")
    print(f"[OK] Generated {GEN_DIR / 'table_compiletime.tex'}")

    # Generate table_reference.tex if reference_baselines.csv exists
    if REF_CSV.exists():
        ref_hash = compute_sha256(REF_CSV)
        print(f"[INTEGRITY] Reference baselines hash: sha256:{ref_hash}")
        ref_rows = []
        with open(REF_CSV, "r", encoding="utf-8") as f:
            reader = csv.DictReader(f)
            ref_rows = list(reader)
        table_ref_tex = generate_table_reference(ref_rows, data_by_bench, ref_hash)
        (GEN_DIR / "table_reference.tex").write_text(table_ref_tex, encoding="utf-8")
        print(f"[OK] Generated {GEN_DIR / 'table_reference.tex'}")

    print("\n[SUCCESS] All LaTeX tables successfully generated from verifiable CSV data.")

if __name__ == "__main__":
    main()
